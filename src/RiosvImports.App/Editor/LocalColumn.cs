namespace RiosvImports.App.Editor;

/// <summary>Какво прави една служебна колона.</summary>
internal enum LocalColumnKind
{
    /// <summary>Показва отметка или бележка. Пази се в базата, не влиза в XML.</summary>
    Text,

    /// <summary>Копче на всеки ред.</summary>
    Button
}

/// <summary>
/// Колона, каквато схемата не познава.
///
/// Отчетът към НИСО не знае нищо за това дали редът вече е пренесен в друг
/// раздел — това е сведение за човека, който попълва, а не за държавата.
/// Затова такива колони живеят само тук и в местната база: износът минава по
/// колоните от плана на листа и просто не ги вижда.
///
/// Имената им започват с две долни черти, за да не могат никога да се
/// сблъскат с име на атрибут от схемата.
/// </summary>
/// <param name="Name">Името в базата — с представка „__“.</param>
/// <param name="Header">Заглавието на колоната, а при копче — надписът върху него.</param>
internal sealed record LocalColumn(
    string Name,
    string Header,
    LocalColumnKind Kind,
    int Width,
    string? Tip = null)
{
    /// <summary>
    /// Колона, която се пази, но не се показва.
    ///
    /// Връзката между реда и редовете, създадени от него, е такава: тя не е
    /// сведение за човека, а за програмата, и колона с осем случайни знака
    /// само би заемала място.
    /// </summary>
    public bool Hidden { get; init; }

    /// <summary>
    /// Колона, в която човек пише сам — със същите жестове като в колоните на
    /// схемата: клавиатура, залепване, Ctrl+D, Delete.
    ///
    /// Служебните колони по начало само показват: те са сведение за реда, а не
    /// данни от него. Договорът на предаването е данни — той просто не е на
    /// НИСО.
    /// </summary>
    public bool Editable { get; init; }
}
